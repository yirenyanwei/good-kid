function w(unit: number, word: string, pinyin: string): WordZhItem {
  return {
    id: `zw-${G}-${V}-u${unit}-${word}`,
    grade: G,
    volume: V,
    unit,
    word,
    pinyin,
    chars: word.split('').map((c) => ({ c, writable: true })),
  }
}

