function h(unit: number, hanzi: string, pinyin: string, speakText?: string): HanziItem {
  return {
    id: `zh-${G}-${V}-u${unit}-${hanzi}`,
    grade: G,
    volume: V,
    unit,
    hanzi,
    pinyin,
    klass: 1,
    ...(speakText ? { speakText } : {}),
  }
}

